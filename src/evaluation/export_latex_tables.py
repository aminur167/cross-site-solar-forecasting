"""
Automated LaTeX Table Synchronizer
==================================
Converts serialized experimental JSON results into publication-ready
booktabs LaTeX tables formatted for Elsevier and IEEE energy journals.
"""

import os
import json
from typing import Dict, Any, List


"""
Automated LaTeX Table Synchronizer
==================================
Converts serialized experimental JSON results into publication-ready
booktabs LaTeX tables formatted for Elsevier and IEEE energy journals.
Synchronizes Table 1, Table 2, Table 3, Table 4, and Table 5.
"""

import os
import json
from typing import Dict, Any, List


def export_all_tables(results_dir: str = "experiments/results", tables_dir: str = "tables"):
    os.makedirs(tables_dir, exist_ok=True)

    # -------------------------------------------------------------
    # Table 1: Baseline Benchmark (Site A Within-Site)
    # -------------------------------------------------------------
    baseline_path = os.path.join(results_dir, "baseline_benchmark_results.json")
    if os.path.exists(baseline_path):
        with open(baseline_path, "r") as f:
            data = json.load(f)

        out_tex = os.path.join(tables_dir, "table1_baseline_benchmark.tex")
        with open(out_tex, "w") as f:
            f.write("% Auto-generated by export_latex_tables.py\n")
            f.write("\\begin{table}[htbp]\n")
            f.write("\\centering\n")
            f.write("\\caption{Benchmark 1-hour ahead solar PV power forecasting performance on within-site evaluation (Site A, 50~kWp, $N=1,159$ daytime active test hours).}\n")
            f.write("\\label{tab:baseline_benchmark}\n")
            f.write("\\begin{tabular}{lccccc}\n")
            f.write("\\toprule\n")
            f.write("Model & MAE (kW) & RMSE (kW) & nMAE (\\%) & nRMSE (\\%) & Skill Score (\\%) \\\\\n")
            f.write("\\midrule\n")

            for model_name, metrics in data.items():
                clean_name = model_name.replace("_", " ")
                m = metrics.get("daytime", metrics) # Use daytime primary
                mae = m.get("MAE", 0.0)
                rmse = m.get("RMSE", 0.0)
                nmae = m.get("nMAE_pct", 0.0)
                nrmse = m.get("nRMSE_pct", 0.0)
                ss = m.get("Skill_Score_vs_Persist", 0.0) * 100.0

                if "Gradient_Boosting" in model_name or "LightGBM" in model_name:
                    f.write(f"\\textbf{{{clean_name}}} & \\textbf{{{mae:.4f}}} & \\textbf{{{rmse:.4f}}} & \\textbf{{{nmae:.2f}}} & \\textbf{{{nrmse:.2f}}} & \\textbf{{{ss:+.2f}}} \\\\\n")
                else:
                    f.write(f"{clean_name} & {mae:.4f} & {rmse:.4f} & {nmae:.2f} & {nrmse:.2f} & {ss:+.2f} \\\\\n")

            f.write("\\bottomrule\n")
            f.write("\\end{tabular}\n")
            f.write("\\end{table}\n")
        print(f"[INFO] Exported synchronized Table 1 to {out_tex}")

    # -------------------------------------------------------------
    # Table 2: Cross-Site Generalization and Adaptation Frontier
    # -------------------------------------------------------------
    adapt_path = os.path.join(results_dir, "cross_site_adaptation_results.json")
    if os.path.exists(adapt_path):
        with open(adapt_path, "r") as f:
            data = json.load(f)

        out_tex = os.path.join(tables_dir, "table2_cross_site_adaptation.tex")
        with open(out_tex, "w") as f:
            f.write("% Auto-generated by export_latex_tables.py\n")
            f.write("\\begin{table}[htbp]\n")
            f.write("\\centering\n")
            f.write("\\caption{Cross-site transfer learning and data-efficient target adaptation results from Source Site A to Target Site B (50~kWp, test horizon: March--May 2026, $N=1,052$ daytime active hours).}\n")
            f.write("\\label{tab:cross_site_adaptation}\n")
            f.write("\\begin{tabular}{lcccccc}\n")
            f.write("\\toprule\n")
            f.write("\\textbf{Regime} & \\textbf{Target Budget} & \\textbf{nMAE (\\%)} & \\textbf{nRMSE (\\%)} & \\textbf{$R^2$} & \\textbf{Skill Score} & \\textbf{Error Reduction} \\\\\n")
            f.write("\\midrule\n")

            p_m = data["Persistence_Baseline"].get("daytime", data["Persistence_Baseline"])
            o_m = data["Target_Oracle_Full"].get("daytime", data["Target_Oracle_Full"])
            p_nmae = p_m["nMAE_pct"]

            f.write(f"Persistence Baseline & --- & {p_m['nMAE_pct']:.2f} & {p_m['nRMSE_pct']:.2f} & {p_m['R2']:.4f} & 0.0000 & Reference \\\\\n")
            f.write(f"Target Oracle (Full Data) & $\\sim$315 days & {o_m['nMAE_pct']:.2f} & {o_m['nRMSE_pct']:.2f} & {o_m['R2']:.4f} & {o_m['Skill_Score_vs_Persist']:+.4f} & Ceiling \\\\\n")
            f.write("\\midrule\n")
            f.write("\\multicolumn{7}{l}{\\textit{Target-Only from Scratch (No Transfer Learning)}} \\\\\n")

            budgets = [1, 3, 7, 14]
            for k in budgets:
                entry = data["Zero_Shot_and_Adaptation"][f"k_{k}_days"]
                to = entry["target_only_metrics"].get("daytime", entry["target_only_metrics"])
                rel_p = ((p_nmae - to['nMAE_pct']) / p_nmae) * 100.0
                note = "Overfitting" if to['R2'] < 0.70 else f"{rel_p:+.1f}\\% vs Persist"
                f.write(f"Target-Only & {k} day{'s' if k > 1 else ''} & {to['nMAE_pct']:.2f} & {to['nRMSE_pct']:.2f} & {to['R2']:.4f} & {to['Skill_Score_vs_Persist']:+.4f} & {note} \\\\\n")

            f.write("\\midrule\n")
            f.write("\\multicolumn{7}{l}{\\textit{Transfer Learning \\& Target Adaptation (Source + Target Budget)}} \\\\\n")
            
            zs = data["Zero_Shot_and_Adaptation"]["k_0_days"]["transfer_adapted_metrics"].get("daytime", data["Zero_Shot_and_Adaptation"]["k_0_days"]["transfer_adapted_metrics"])
            rel_zs = ((p_nmae - zs['nMAE_pct']) / p_nmae) * 100.0
            f.write(f"Zero-Shot Transfer & 0 days & \\textbf{{{zs['nMAE_pct']:.2f}}} & \\textbf{{{zs['nRMSE_pct']:.2f}}} & \\textbf{{{zs['R2']:.4f}}} & \\textbf{{{zs['Skill_Score_vs_Persist']:+.4f}}} & {rel_zs:+.1f}\\% vs Persist \\\\\n")

            for k in budgets:
                entry = data["Zero_Shot_and_Adaptation"][f"k_{k}_days"]
                tl = entry["transfer_adapted_metrics"].get("daytime", entry["transfer_adapted_metrics"])
                to = entry["target_only_metrics"].get("daytime", entry["target_only_metrics"])
                rel_scratch = ((to['nMAE_pct'] - tl['nMAE_pct']) / to['nMAE_pct']) * 100.0
                f.write(f"Adapted Transfer & {k} day{'s' if k > 1 else ''} & {tl['nMAE_pct']:.2f} & {tl['nRMSE_pct']:.2f} & {tl['R2']:.4f} & {tl['Skill_Score_vs_Persist']:+.4f} & $\\mathbf{{{ -rel_scratch:.1f}\\%}}$ vs Scratch \\\\\n")

            f.write("\\bottomrule\n")
            f.write("\\end{tabular}\n")
            f.write("\\end{table}\n")
        print(f"[INFO] Exported synchronized Table 2 to {out_tex}")

    # -------------------------------------------------------------
    # Table 3: Uncertainty Quantification and Sensor Robustness
    # -------------------------------------------------------------
    uncert_path = os.path.join(results_dir, "uncertainty_robustness_results.json")
    if os.path.exists(uncert_path):
        with open(uncert_path, "r") as f:
            data = json.load(f)

        out_tex = os.path.join(tables_dir, "table3_uncertainty_robustness.tex")
        with open(out_tex, "w") as f:
            f.write("% Auto-generated by export_latex_tables.py\n")
            f.write("\\begin{table}[htbp]\n")
            f.write("\\centering\n")
            f.write("\\caption{Conformalized Quantile Regression (CQR) uncertainty calibration (nominal 90\\% prediction interval) and sensor-availability degradation stress-tests on unseen Target Site B holdout ($N=1,052$ daytime active hours).}\n")
            f.write("\\label{tab:uncertainty_robustness}\n")
            f.write("\\begin{tabular}{lccccc}\n")
            f.write("\\toprule\n")
            f.write("\\textbf{Regime / Degradation Scenario} & \\textbf{nMAE (\\%)} & \\textbf{nRMSE (\\%)} & \\textbf{PICP (\\%)} & \\textbf{MPIW} & \\textbf{Winkler Score} \\\\\n")
            f.write("\\midrule\n")
            f.write("\\multicolumn{6}{l}{\\textit{Panel A: Uncertainty Calibration Regimes (100\\% Sensors Available)}} \\\\\n")

            cal_regimes = [
                ("Raw Quantile Regression (No Conformal)", "Raw_Quantile_Regression"),
                ("Source-Calibrated CQR (Site A Calibration)", "Source_Calibrated_CQR"),
                ("Target-Adapted CQR (14-day Local Calibration)", "Target_Adapted_CQR")
            ]
            for label, key in cal_regimes:
                reg_data = data["Uncertainty_Calibration_Regimes"][key]
                u = reg_data.get("daytime", reg_data)
                picp = u["PICP_pct"]
                mpiw = u["MPIW"]
                winkler = u["Winkler_Score"]
                if key == "Target_Adapted_CQR":
                    f.write(f"{label} & 8.50 & 11.84 & \\textbf{{{picp:.2f}}} & {mpiw:.4f} & \\textbf{{{winkler:.4f}}} \\\\\n")
                else:
                    f.write(f"{label} & 8.50 & 11.84 & {picp:.2f} & {mpiw:.4f} & {winkler:.4f} \\\\\n")

            f.write("\\midrule\n")
            f.write("\\multicolumn{6}{l}{\\textit{Panel B: Sensor Availability Shifts \\& Telemetry Degradation}} \\\\\n")

            stress_data = data["Sensor_Availability_Stress_Test"]
            for scen_name, scen_res in stress_data.items():
                p = scen_res["point_metrics"].get("daytime", scen_res["point_metrics"])
                u = scen_res["uncertainty_metrics"].get("daytime", scen_res["uncertainty_metrics"])
                nmae = p["nMAE_pct"]
                nrmse = p["nRMSE_pct"]
                picp = u["PICP_pct"]
                mpiw = u["MPIW"]
                winkler = u.get("Winkler_Score", 0.0)

                clean_scen = scen_name.replace("%", "\\%")
                if "Complete Telemetry" in scen_name:
                    f.write(f"\\textbf{{{clean_scen}}} & \\textbf{{{nmae:.2f}}} & \\textbf{{{nrmse:.2f}}} & \\textbf{{{picp:.2f}}} & \\textbf{{{mpiw:.4f}}} & {winkler:.4f} \\\\\n")
                else:
                    f.write(f"{clean_scen} & {nmae:.2f} & {nrmse:.2f} & {picp:.2f} & {mpiw:.4f} & {winkler:.4f} \\\\\n")

            f.write("\\bottomrule\n")
            f.write("\\end{tabular}\n")
            f.write("\\end{table}\n")
        print(f"[INFO] Exported synchronized Table 3 to {out_tex}")

    # -------------------------------------------------------------
    # Table 5: Deep Learning Benchmark vs GBDT
    # -------------------------------------------------------------
    dl_path = os.path.join(results_dir, "deep_learning_and_statistics.json")
    if os.path.exists(dl_path):
        with open(dl_path, "r") as f:
            data = json.load(f)

        out_tex = os.path.join(tables_dir, "table5_deep_learning_benchmark.tex")
        with open(out_tex, "w") as f:
            f.write("% Auto-generated by export_latex_tables.py\n")
            f.write("\\begin{table}[htbp]\n")
            f.write("\\centering\n")
            f.write("\\caption{Comparative performance of recurrent (LSTM), convolutional (TCN), and gradient boosted decision tree (LightGBM) architectures on unseen Target Site B holdout ($N=1,052$ daytime active sequential samples), including stationary block bootstrap 95\\% confidence intervals and Diebold-Mariano hypothesis tests with Newey-West HAC spectral estimation.}\n")
            f.write("\\label{tab:deep_learning_benchmark}\n")
            f.write("\\begin{tabular}{lccccc}\n")
            f.write("\\toprule\n")
            f.write("\\textbf{Model Architecture} & \\textbf{nMAE (\\%)} & \\textbf{95\\% CI (nMAE)} & \\textbf{nRMSE (\\%)} & \\textbf{DM Statistic vs. GBDT} & \\textbf{$p$-value} \\\\\n")
            f.write("\\midrule\n")

            for name, entry in data.items():
                m = entry.get("daytime", entry.get("metrics", {}))
                nmae = m.get("nMAE_pct", 0.0)
                nrmse = m.get("nRMSE_pct", 0.0)
                ci = entry.get("confidence_intervals", {}).get("nMAE_CI_pct", [0.0, 0.0])
                ci_str = f"[{ci[0]:.2f}, {ci[1]:.2f}]"
                dm_info = entry.get("diebold_mariano_vs_gbdt", {})
                dm_stat = dm_info.get("dm_stat", 0.0)
                p_str = dm_info.get("p_value_str", str(dm_info.get("p_val", "---")))

                if "LightGBM" in name:
                    f.write(f"\\textbf{{{name}}} & \\textbf{{{nmae:.2f}}} & \\textbf{{{ci_str}}} & \\textbf{{{nrmse:.2f}}} & --- & Reference \\\\\n")
                else:
                    star = "$^{***}$" if "< 0.0001" in str(p_str) or dm_info.get("raw_p_value", 1.0) < 0.001 else "$^{**}$" if dm_info.get("raw_p_value", 1.0) < 0.01 else ""
                    f.write(f"{name} & {nmae:.2f} & {ci_str} & {nrmse:.2f} & {dm_stat:.4f} & $p = {p_str}${star} \\\\\n")

            f.write("\\midrule\n")
            f.write("\\multicolumn{6}{l}{\\footnotesize $^{**}p < 0.01$, $^{***}p < 0.001$. Negative DM statistic indicates LightGBM has statistically significantly lower loss.} \\\\\n")
            f.write("\\bottomrule\n")
            f.write("\\end{tabular}\n")
            f.write("\\end{table}\n")
        print(f"[INFO] Exported synchronized Table 5 to {out_tex}")


if __name__ == "__main__":
    export_all_tables()
